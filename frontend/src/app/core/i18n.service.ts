@Injectable({ providedIn: 'root' })
export class I18nService {
  private readonly LS_KEY = 'locale';
  private readonly _lang = signal<Lang>(this.detect());
  private readonly prefs = inject(PreferencesService);

  readonly lang = this._lang.asReadonly();
  readonly t = computed(() => {
    const l = this._lang();
    return (key: string, params?: Record<string, string>) => {
      let v = DICT[l][key] ?? DICT['en'][key] ?? key;
      if (params) for (const [k, val] of Object.entries(params)) v = v.replace(`{${k}}`, val);
      return v;
    };
  });

  constructor() {
    effect(() => document.documentElement.lang = this._lang());

    // sync depuis BDD quand dispo - source unique PreferencesService
    effect(() => {
      const p = this.prefs.resource.value();
      if (p?.locale && SUPPORTED.includes(p.locale as Lang)) {
        if (p.locale !== this._lang()) {
          this._lang.set(p.locale as Lang);
          localStorage.setItem(this.LS_KEY, p.locale);
        }
      }
    });
  }

  private detect(): Lang {
    const saved = localStorage.getItem(this.LS_KEY) as Lang | null;
    if (saved && SUPPORTED.includes(saved)) return saved;
    const nav = navigator.language.toLowerCase();
    if (nav.startsWith('es')) return 'es';
    if (nav.startsWith('de')) return 'de';
    if (nav.startsWith('zh')) return 'zh';
    if (nav.startsWith('en')) return 'en';
    // défaut fr pour correspondre au backend
    return 'fr';
  }

  setLang(l: Lang) {
    if (!SUPPORTED.includes(l)) return;
    this._lang.set(l);
    localStorage.setItem(this.LS_KEY, l);
    this.prefs.update({ locale: l } as any).catch(() => {});
  }
}
